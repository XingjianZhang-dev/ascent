#!/usr/bin/env python3
"""Assemble the public release tree (Phase 4) from the development tree.

Rules (Phase 4 companion, §3):

* ``artifacts/``, ``configs/``, ``data/`` manifests: byte-identical copies
  (``shutil.copy2``); nothing is reformatted or re-rendered.
* Not included: model weights (``artifacts/checkpoints/``); benchmark row
  bodies — every BABILong/RULER ``*.jsonl`` under ``data/`` and
  ``artifacts/*_source/``, and the result archives that embed such files; the
  frozen backup archives; caches, virtualenvs, ``.DS_Store``.
* For every BABILong panel whose bodies are withheld, a ``<panel>.ids.json``
  with the ``row_id`` and ``task`` of each row, plus the panel and source
  hashes, is written next to the manifest so the panel can be rebuilt and
  verified from the pinned upstream revision.
* Synthetic panels generated by this project (``data/posttraining_*``) are
  included in full.
* After copying, every ``SHA256SUMS*`` / ``*.sha256`` manifest in the tree is
  re-verified and the outcome written to ``reports/RELEASE_TREE_INTEGRITY.txt``.
* Files larger than 50 MB are reported; nothing over 100 MB is allowed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

DEV = Path(__file__).resolve().parents[1]

TOP_LEVEL_COPY = ["ascent", "experiments", "tests", "configs", "reproduction", "artifacts_revision", "pyproject.toml", "Makefile", "PREREGISTRATION_TIMELINE.md"]
DOCS_COPY = ["EXPERIMENT_LEDGER.md", "EXPERIMENT_PROTOCOL.md", "ASCENT_TASK_SCOPE_PROTOCOL.md", "DESIGN_RISKS.md", "DEV_HISTORY_LOG.txt", "AROUND_7B_COMPLETION_AUDIT.md"]
PAPER_COPY = ["paper/data/evidence", "paper/generated"]
RELEASE_DOCS = ["README.md", "LICENSE", "LICENSE-DATA", "THIRD_PARTY_NOTICES.md", "CITATION.cff", "VERIFICATION.md", "AI_ASSISTANCE.md", "WRITER_SCHEMA_AND_SCOPE.md", ".gitleaks.toml"]

HELD_BACK_ARCHIVES = [
    "artifacts/remote_results/ascent_core_reproduction_ffe6c78.tar.gz",
    "artifacts/remote_results/ruler_qa2_headroom_052cd2a/ruler_qa2_headroom_052cd2a_node1.tar.gz",
    "artifacts/remote_results/ruler_qa2_hotpot_dualpath_factorial_8566dae/ruler_qa2_hotpot_dualpath_factorial_8566dae_node1.tar.gz",
    "artifacts/remote_results/ruler_qa2_hotpot_fullstate_factorial_59cf4e6/ruler_qa2_hotpot_fullstate_factorial_59cf4e6_node1.tar.gz",
]
# Development-tree files that are macOS "dataless" placeholders (content evicted by the
# file provider and not rehydratable). The release copies the identical member of the
# transfer archive the loose file was originally extracted from; see RELEASE_TREE_INTEGRITY.txt.
RECOVER_FROM_ARCHIVE = {
    "artifacts/remote_results/babilong_8k_confirm/node2/panel1_smollm2-360m-node2.json": (
        "artifacts/remote_results/babilong_8k_confirm_440ef7f.tar.gz",
        "babilong_8k_confirm/node2/panel1_smollm2-360m-node2.json",
    ),
}
EXCLUDE_DIR_NAMES = {"__pycache__", ".pytest_cache", ".venv", ".git", "checkpoints", ".mypy_cache", ".ruff_cache"}
EXCLUDE_FILE_NAMES = {".DS_Store"}
SECRET_PATTERN = re.compile(rb"(hf_[A-Za-z0-9]{20,}|sk-[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|gho_[A-Za-z0-9]{20,}|BEGIN (RSA|OPENSSH|EC) PRIVATE KEY|AKIA[0-9A-Z]{16})")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def copy_tree(src: Path, dst: Path, skip_file=None) -> int:
    count = 0
    for root, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in EXCLUDE_DIR_NAMES]
        rel = Path(root).relative_to(src)
        for name in files:
            if name in EXCLUDE_FILE_NAMES or name.endswith((".pyc", ".pyo")):
                continue
            source = Path(root) / name
            if skip_file and skip_file(source):
                continue
            target = dst / rel / name
            target.parent.mkdir(parents=True, exist_ok=True)
            rel_source = str(source.relative_to(DEV))
            if rel_source in RECOVER_FROM_ARCHIVE:
                import tarfile

                archive, member = RECOVER_FROM_ARCHIVE[rel_source]
                with tarfile.open(DEV / archive) as tar:
                    handle = tar.extractfile(member)
                    assert handle is not None
                    target.write_bytes(handle.read())
                RECOVERED.append(f"{rel_source}: development copy is a dataless placeholder; released bytes are member {member!r} of {archive} (sha256={sha256_file(target)}, {target.stat().st_size} bytes)")
            else:
                shutil.copy2(source, target)
            count += 1
    return count


RECOVERED: list[str] = []


def is_benchmark_body(path: Path) -> bool:
    rel = str(path.relative_to(DEV))
    if rel.startswith("data/posttraining_"):
        return False
    if rel.startswith("data/") and path.suffix == ".jsonl":
        return True
    if rel.startswith("artifacts/") and "_source/" in rel and path.suffix == ".jsonl":
        return True
    # The BGE-M3 retrieval caches store three ranked passages per row (the same fragments that
    # appear as retained_facts in the released records), so they are released; their SHA-256
    # values are pinned in the ablation run configuration.
    return rel in HELD_BACK_ARCHIVES


def write_panel_ids(src_dir: Path, dst_dir: Path) -> int:
    written = 0
    for panel in sorted(src_dir.glob("*.jsonl")):
        rows = [json.loads(line) for line in panel.read_text().splitlines() if line.strip()]
        ids = [{"row_id": r.get("row_id"), "task": r.get("task")} for r in rows]
        out = dst_dir / f"{panel.stem}.ids.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps({"panel": panel.stem, "panel_sha256": sha256_file(panel), "rows": len(rows), "row_ids": ids,
                                   "note": "row bodies are not redistributed; rebuild with the construction scripts from the pinned upstream revision and verify panel_sha256"}, indent=2) + "\n")
        written += 1
    return written


def verify_manifests(tree: Path) -> list[str]:
    lines = []
    manifests = sorted(p for p in tree.rglob("*") if p.is_file() and (p.name.startswith("SHA256SUMS") or p.suffix == ".sha256" or p.name == "MANIFEST.sha256"))
    total_ok = total_missing = total_bad = 0
    for manifest in manifests:
        ok = missing = bad = 0
        for line in manifest.read_text().splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            digest, _, name = line.partition("  ")
            name = name.strip().lstrip("*")
            if not re.fullmatch(r"[0-9a-f]{64}", digest.strip()):
                continue
            candidates = [manifest.parent / name, tree / name, manifest.parent / Path(name).name]
            target = next((c for c in candidates if c.is_file()), None)
            if target is None:
                missing += 1
                continue
            if sha256_file(target) == digest.strip():
                ok += 1
            else:
                bad += 1
        total_ok += ok; total_missing += missing; total_bad += bad
        lines.append(f"{manifest.relative_to(tree)}: ok={ok} missing={missing} mismatch={bad}")
    lines.insert(0, f"manifests={len(manifests)} files_ok={total_ok} files_missing_from_release={total_missing} files_mismatching={total_bad}")
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-docs", type=Path, default=DEV / "release_docs")
    parser.add_argument("--target", type=Path, default=DEV / "release/ascent")
    parser.add_argument("--clean", action="store_true", help="remove the target tree first (keeps .git)")
    args = parser.parse_args()
    target = args.target
    if args.clean and target.exists():
        for child in target.iterdir():
            if child.name == ".git":
                continue
            shutil.rmtree(child) if child.is_dir() else child.unlink()
    target.mkdir(parents=True, exist_ok=True)

    counts = {}
    for item in TOP_LEVEL_COPY:
        src = DEV / item
        if src.is_dir():
            counts[item] = copy_tree(src, target / item)
        elif src.is_file():
            (target / item).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, target / item)
            counts[item] = 1
    (target / "docs").mkdir(exist_ok=True)
    for name in DOCS_COPY:
        if (DEV / "docs" / name).is_file():
            shutil.copy2(DEV / "docs" / name, target / "docs" / name)
    for item in PAPER_COPY:
        counts[item] = copy_tree(DEV / item, target / item)
    # the revision changelog is cited by the response letter as paper/CHANGELOG_REVISION1.md
    shutil.copy2(DEV / "paper/CHANGELOG_REVISION1.md", target / "paper/CHANGELOG_REVISION1.md")
    counts["paper/CHANGELOG_REVISION1.md"] = 1
    counts["reports"] = copy_tree(DEV / "reports", target / "reports", skip_file=lambda p: p.suffix == ".html")
    counts["artifacts"] = copy_tree(DEV / "artifacts", target / "artifacts", skip_file=is_benchmark_body)
    counts["data"] = copy_tree(DEV / "data", target / "data", skip_file=is_benchmark_body)
    ids = 0
    for d in sorted((DEV / "data").iterdir()):
        if d.is_dir() and d.name.startswith("babilong") and any(d.glob("*.jsonl")):
            ids += write_panel_ids(d, target / "data" / d.name)
    for d in sorted((DEV / "data").glob("ruler_*")):
        for jl in d.rglob("*.jsonl"):
            rel = jl.relative_to(DEV / "data")
            out = target / "data" / rel.with_suffix(".sha256.json")
            out.parent.mkdir(parents=True, exist_ok=True)
            rows = sum(1 for line in jl.read_text().splitlines() if line.strip())
            out.write_text(json.dumps({"path": str(rel), "sha256": sha256_file(jl), "rows": rows, "note": "RULER task file generated from the pinned NVIDIA/RULER commit and seed recorded in the config; not redistributed"}, indent=2) + "\n")
            ids += 1
    counts["panel_id_files"] = ids
    for name in RELEASE_DOCS:
        src = args.release_docs / name
        if src.is_file():
            shutil.copy2(src, target / name)
    (target / ".gitignore").write_text("__pycache__/\n*.py[cod]\n.pytest_cache/\n.venv*/\n.DS_Store\n*.egg-info/\nrecomputed/\n")
    (target / ".gitattributes").write_text("*.json -diff\n*.csv -diff\n*.tar.gz binary\n*.tgz binary\n*.npz binary\n")

    integrity = verify_manifests(target)
    held = [f"{p}  sha256={sha256_file(DEV / p)}  bytes={(DEV / p).stat().st_size}" for p in HELD_BACK_ARCHIVES]
    big = sorted(((p.stat().st_size, str(p.relative_to(target))) for p in target.rglob("*") if p.is_file() and p.stat().st_size > 50_000_000), reverse=True)
    secrets = []
    for p in target.rglob("*"):
        if p.is_file() and p.suffix not in {".gz", ".tgz", ".npz", ".pdf", ".png", ".bin"} and p.stat().st_size < 50_000_000:
            if SECRET_PATTERN.search(p.read_bytes()):
                secrets.append(str(p.relative_to(target)))
    total_bytes = sum(p.stat().st_size for p in target.rglob("*") if p.is_file() and ".git" not in p.parts)
    report = [
        f"# Release tree integrity — generated {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"source HEAD: {subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=DEV, capture_output=True, text=True).stdout.strip()}",
        f"target: {target}",
        f"copied: {json.dumps(counts)}",
        f"total bytes (excluding .git): {total_bytes} ({total_bytes/1e6:.1f} MB)",
        "", "## SHA-256 manifests re-verified against the copied files", *integrity,
        "", "## Held back (benchmark row bodies embedded) — available to the editor on request", *held,
        "", "## Recovered from transfer archives (development copy unreadable)", *(RECOVERED or ["none"]),
        "", "## Files over 50 MB", *([f"{s} {n}" for s, n in big] or ["none"]),
        "", "## Credential-pattern scan", "clean" if not secrets else "MATCHES: " + ", ".join(secrets),
    ]
    (target / "reports" / "RELEASE_TREE_INTEGRITY.txt").write_text("\n".join(report) + "\n")
    print("\n".join(report))
    if any(s > 100_000_000 for s, _ in big) or secrets or "files_mismatching=0" not in integrity[0]:
        raise SystemExit("release tree checks FAILED")


if __name__ == "__main__":
    main()
