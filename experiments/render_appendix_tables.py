#!/usr/bin/env python3
"""Render the revision-1 appendix tables from immutable analysis records.

Outputs (all under ``paper/generated/``):

* ``factorial_cells.tex`` — Appendix A: mean NLL gain and 95% t_8 interval in
  all nine Qwen2.5 reader x state cells, from
  ``artifacts/sum_numeric_candidate/confirmation_analysis.json``.
* ``babilong_4k_8k_results.tex`` — Appendix C: SmolLM2 official BABILong
  QA1--QA3 accuracy gains and adjacent increments at 4K and 8K, from
  ``artifacts/remote_results/babilong_{4k_scale_confirm,8k_confirm}/analysis.json``.
* ``smollm2_factorials.tex`` — Appendix C: the two SmolLM2 3x3 factorials
  (free-generation QA1--QA3 with 1/2/3 slots; certified QA7--QA8 with 1/2/8
  slots): all nine cells, diagonal increments and same-refinement interactions.
* ``model_revisions.tex`` — Appendix E: every pinned checkpoint with its
  Hugging Face revision, shard count and total bytes, collected from
  ``configs/*.json``.

Values are printed with the manuscript's conventions (three or four decimals;
intervals in brackets). Nothing under ``artifacts/`` is written.
"""

from __future__ import annotations

import argparse
import glob
import json
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(path: str) -> dict:
    return json.loads((ROOT / path).read_text())


def d(value: float, places: int = 3) -> str:
    """Manuscript style: round half up on the decimal value, leading zero dropped below one.

    Same rule as ``decimal()`` in render_paper_additional_tables.py. Panel means are exact
    decimals (e.g. .44375 for a 5-panel mean of 80-row accuracies), so ``f"{value:.4f}"``,
    which rounds the binary double, would print .4437 where the manuscript convention gives .4438.
    """
    text = str(Decimal(f"{value:.12f}").quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP))
    if text.startswith("0."):
        return text[1:]
    if text.startswith("-0."):
        return "$-$" + text[2:]
    if text.startswith("-"):
        return "$-$" + text[1:]
    return text


def ci(summary: dict, places: int = 3) -> str:
    return f"{d(summary['mean'], places)} [{d(summary['ci95_low'], places)},{d(summary['ci95_high'], places)}]"


def factorial_cells() -> str:
    a = load("artifacts/sum_numeric_candidate/confirmation_analysis.json")
    readers = [("qwen2p5-1p5b-instruct", "1.5B"), ("qwen2p5-3b-instruct", "3B"), ("qwen2p5-7b-instruct", "7B")]
    slots = [2, 3, 5]
    lines = ["% Auto-generated by experiments/render_appendix_tables.py; do not edit.",
             r"\begin{tabular}{lccc}", r"\toprule", "Reader & $K=2$ & $K=3$ & $K=5$ \\\\", r"\midrule"]
    for key, label in readers:
        cells = [a["cells"][f"{key}@k{k}"]["gain_nll"] for k in slots]
        marks = ["$\\star$" if (label, k) in {("1.5B", 2), ("3B", 3), ("7B", 5)} else "" for k in slots]
        lines.append(f"{label} & " + " & ".join(f"{ci(c)}{m}" for c, m in zip(cells, marks)) + " \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def babilong_4k_8k() -> str:
    labels = {"smollm2-135m": "135M", "smollm2-360m-node2": "360M", "smollm2-1p7b": "1.7B"}
    lines = ["% Auto-generated by experiments/render_appendix_tables.py; do not edit.",
             r"\begin{tabular}{llccccc}", r"\toprule",
             "Context & Panels & Gain 135M & Gain 360M & Gain 1.7B & Incr.\\ 135M$\\to$360M & Incr.\\ 360M$\\to$1.7B \\\\", r"\midrule"]
    for context, path in (("4K", "artifacts/remote_results/babilong_4k_scale_confirm/analysis.json"),
                          ("8K", "artifacts/remote_results/babilong_8k_confirm/analysis.json")):
        a = load(path)
        gains = [ci(a["endpoint_gain_panel_t_intervals"][e], 4) for e in a["endpoints"]]
        adj = list(a["adjacent_gain_increment_panel_t_intervals"].values())
        lines.append(f"{context} & {len(a['panels'])} & " + " & ".join(gains) + " & " + " & ".join(ci(x, 4) for x in adj) + " \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def smollm2_factorials(out_dir: Path | None = None) -> str:
    gen = load("artifacts/remote_results/babilong_8k_generative_factorial_audit_693c414/factorial_analysis.json")
    cert = load("artifacts/remote_results/babilong_qa78_certified_factorial_ab4222a/factorial_analysis.json")
    lines = ["% Auto-generated by experiments/render_appendix_tables.py; do not edit.",
             r"\begin{tabular}{llccc}", r"\toprule", "Study & Reader & Slot 1 & Slot 2 & Slot 3/8 \\\\", r"\midrule"]
    for study, a, readers, slots in (
        ("Free generation QA1--QA3 (8K, 3 panels)", gen, [("smollm2-135m-instruct", "135M"), ("smollm2-360m-instruct", "360M"), ("smollm2-1p7b-instruct", "1.7B")], [1, 2, 3]),
        ("Certified QA7--QA8 (8K, 5 panels)", cert, [("smollm2-135m", "135M"), ("smollm2-360m-node2", "360M"), ("smollm2-1p7b", "1.7B")], [1, 2, 8]),
    ):
        first = True
        for key, label in readers:
            cells = [a["cells"][key][str(k)]["absolute_gain"] for k in slots]
            diag = {("135M", slots[0]), ("360M", slots[1]), ("1.7B", slots[2])}
            row = " & ".join(f"{ci(c, 4)}{'$\\star$' if (label, k) in diag else ''}" for c, k in zip(cells, slots))
            lines.append(f"{study if first else ''} & {label} & {row} \\\\")
            first = False
        lines.append(r"\midrule")
    lines.pop()
    lines += [r"\bottomrule", r"\end{tabular}"]
    # second block: diagonal increments and interactions
    inter_lines = ["", r"\vspace{0.5em}", r"\begin{tabular}{lcccc}", r"\toprule",
                   "Study & Diag.\\ incr.\\ 1 & Diag.\\ incr.\\ 2 & Interaction 1 & Interaction 2 \\\\", r"\midrule"]
    g_inter = list(gen["registered_foundation_by_state_interactions"].values())
    g_diag = [gen["cells"]["smollm2-135m-instruct"]["1"]["absolute_gain"], gen["cells"]["smollm2-360m-instruct"]["2"]["absolute_gain"], gen["cells"]["smollm2-1p7b-instruct"]["3"]["absolute_gain"]]
    # diagonal increments for the generative study: paired per panel
    import math
    def paired(hi: dict, lo: dict) -> dict:
        vals = [b - a for a, b in zip(lo["values"], hi["values"], strict=True)]
        n = len(vals); mean = sum(vals) / n
        sd = math.sqrt(sum((v - mean) ** 2 for v in vals) / (n - 1)); se = sd / math.sqrt(n)
        from scipy.stats import t as student_t
        crit = float(student_t.ppf(0.975, n - 1))
        return {"mean": mean, "ci95_low": mean - crit * se, "ci95_high": mean + crit * se}
    g_incr = [paired(g_diag[1], g_diag[0]), paired(g_diag[2], g_diag[1])]
    inter_lines.append("Free generation & " + " & ".join(ci(x, 4) for x in g_incr) + " & " + " & ".join(ci(x, 4) for x in g_inter) + " \\\\")
    c_incr = list(cert["diagonal_absolute_gain_adjacent"].values())
    c_inter = [cert["foundation_by_state_interactions"]["smollm2-135m_to_smollm2-360m-node2"]["slots_1_to_2"],
               cert["foundation_by_state_interactions"]["smollm2-360m-node2_to_smollm2-1p7b"]["slots_2_to_8"]]
    inter_lines.append("Certified & " + " & ".join(ci(x, 4) for x in c_incr) + " & " + " & ".join(ci(x, 4) for x in c_inter) + " \\\\")
    inter_lines += [r"\bottomrule", r"\end{tabular}"]
    contrasts = "\n".join(["% Auto-generated by experiments/render_appendix_tables.py; do not edit."] + inter_lines[2:]) + "\n"
    ((out_dir or ROOT / "paper/generated") / "smollm2_factorial_contrasts.tex").write_text(contrasts)
    return "\n".join(lines) + "\n"


def model_revisions() -> str:
    revs: dict[tuple[str, str], tuple[int, int]] = {}
    for path in sorted(glob.glob(str(ROOT / "configs/*.json"))):
        try:
            cfg = json.loads(Path(path).read_text())
        except json.JSONDecodeError:
            continue
        endpoints = cfg.get("endpoints") or []
        if isinstance(endpoints, dict):
            endpoints = list(endpoints.values())
        for e in endpoints:
            if not (isinstance(e, dict) and e.get("repo_id") and e.get("revision")):
                continue
            if len(str(e["revision"])) != 40:
                continue  # descriptive placeholder, not a commit hash
            arts = e.get("model_artifacts") or ([e["model_artifact"]] if e.get("model_artifact") else [])
            revs.setdefault((e["repo_id"], e["revision"]), (len(arts), sum(int(a.get("bytes", 0)) for a in arts)))
    lines = ["% Auto-generated by experiments/render_appendix_tables.py; do not edit.",
             r"\begin{tabular}{llrr}", r"\toprule", "Checkpoint & Hugging Face revision & Shards & Bytes \\\\", r"\midrule"]
    for (repo, rev), (n, b) in sorted(revs.items()):
        shards = str(n) if n else "--"
        size = f"{b:,}" if b else "--"
        lines.append(f"\\texttt{{{repo.replace('_', r'\_')}}} & \\texttt{{{rev[:12]}}} & {shards} & {size} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=ROOT / "paper/generated")
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name, fn in (("factorial_cells.tex", factorial_cells), ("babilong_4k_8k_results.tex", babilong_4k_8k),
                     ("smollm2_factorials.tex", lambda: smollm2_factorials(args.out_dir)), ("model_revisions.tex", model_revisions)):
        (args.out_dir / name).write_text(fn())
        print("written", args.out_dir / name)


if __name__ == "__main__":
    main()
